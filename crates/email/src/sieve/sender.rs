//! FORK: restricts who a Sieve script can send mail as.
//!
//! A script chooses the From header of the vacation replies and notifications
//! it generates (`vacation :from`), and the runtime does not check it. These
//! messages are queued directly, so no submission check sees them either.
//! Only messages whose From is a single address of the account are sent, and
//! they are signed and sent as that address.
//!
//! A redirect keeps the From of the message it forwards, but is sent with the
//! account's envelope sender and signed for its domain. Forwarding a message
//! that claims a From on a domain hosted here would therefore make it pass
//! DMARC at the destination, so such a message is only redirected when its
//! sender was authenticated on arrival.

use crate::message::delivery::{AutogeneratedMessage, SenderAuthentication};
use common::Server;
use compact_str::CompactString;
use mail_parser::{HeaderName, MessageParser};
use sieve::MessageSource;
use trc::{AddContext, SieveEvent};
use utils::DomainPart;

/// Drops the generated replies and notifications that are not from an address
/// of the account, and makes the rest use their From address as their sending
/// identity. `own_addresses` are addresses already known to be the account's:
/// its base address and the one the message was sent to, which is how a
/// sub-address, masked address or catch-all address is accepted.
/// Redirects keep the sender of the message they forward, and are dropped
/// when `unverified_from` is set (see [`unverified_local_from`]).
pub(super) async fn retain_own_senders(
    server: &Server,
    account_id: u32,
    own_addresses: [&str; 2],
    unverified_from: Option<&str>,
    generated: &mut Vec<AutogeneratedMessage>,
    session_id: u64,
) {
    let mut retained = Vec::with_capacity(generated.len());
    for mut message in generated.drain(..) {
        if message.source == MessageSource::Redirect {
            if let Some(from) = unverified_from {
                trc::event!(
                    Sieve(SieveEvent::NotSupported),
                    SpanId = session_id,
                    From = CompactString::from(from),
                    To = message
                        .recipients
                        .iter()
                        .map(|rcpt| trc::Value::String(rcpt.as_str().into()))
                        .collect::<Vec<_>>(),
                    Reason = "Redirected message is from a local domain and was not authenticated.",
                );
                continue;
            }
        } else {
            let from = from_address(&message.message);
            let mut is_own = false;
            if let Some(from) = &from {
                // Only an address listed on the account is looked up. Resolving
                // sub-addresses, masked addresses and catch-alls would accept a
                // masked local part on any hosted domain.
                is_own = own_addresses
                    .iter()
                    .any(|own| own.eq_ignore_ascii_case(from))
                    || matches!(
                        server.account_id_from_email(from, false).await,
                        Ok(Some(id)) if id == account_id
                    );
            }
            match from {
                Some(from) if is_own => message.account_address = from,
                from => {
                    trc::event!(
                        Sieve(SieveEvent::NotSupported),
                        SpanId = session_id,
                        From = CompactString::from(from.unwrap_or_default()),
                        Reason = "Generated message is not from an address of the account.",
                    );
                    continue;
                }
            }
        }
        retained.push(message);
    }
    *generated = retained;
}

/// The address in the From header, when there is exactly one of each.
fn from_address(raw_message: &[u8]) -> Option<String> {
    let message = MessageParser::new().parse(raw_message)?;
    if message.headers().all(HeaderName::From).count() != 1 {
        return None;
    }
    let mut mailboxes = message.from()?.mailboxes();
    let address = mailboxes.next()?.address()?;
    mailboxes.next().is_none().then(|| address.to_lowercase())
}

/// Every address in every From header. A redirect is judged by all of them,
/// as the destination may pick any to evaluate DMARC.
fn from_addresses(raw_message: &[u8]) -> Vec<String> {
    let Some(message) = MessageParser::new().parse(raw_message) else {
        return Vec::new();
    };
    let addresses = message
        .headers()
        .all(HeaderName::From)
        .filter_map(|header| header.value().as_address())
        .flat_map(|addresses| addresses.mailboxes())
        .filter_map(|mailbox| mailbox.address())
        .map(|address| address.to_lowercase())
        .collect();
    addresses
}

/// The From address that keeps `incoming_message` from being redirected: one
/// on a hosted domain, when the sender was not authenticated and the script
/// redirects the message. The message as it arrived is checked, not the copy
/// being redirected: a script that encloses the message sends the copy from
/// the account. Called before anything is delivered, so that a failed lookup
/// defers the message instead of losing the redirect.
pub(super) async fn unverified_local_from(
    server: &Server,
    account_address: &str,
    incoming_message: &[u8],
    sender_authentication: SenderAuthentication,
    generated: &[AutogeneratedMessage],
) -> trc::Result<Option<String>> {
    if sender_authentication == SenderAuthentication::Unauthenticated
        && generated
            .iter()
            .any(|message| message.source == MessageSource::Redirect)
    {
        hosted_from_address(server, account_address, incoming_message).await
    } else {
        Ok(None)
    }
}

/// The first From address on a domain hosted here, or on a domain of the
/// same organization as the account's: the redirect is signed for the
/// account's domain, and relaxed DMARC alignment lets that signature cover
/// the parent, sibling and child domains of it.
async fn hosted_from_address(
    server: &Server,
    account_address: &str,
    raw_message: &[u8],
) -> trc::Result<Option<String>> {
    let account_domain = account_address.try_domain_part().unwrap_or_default();
    for address in from_addresses(raw_message) {
        let domain = address.try_domain_part().unwrap_or_default();
        if same_organization(domain, account_domain)
            || server
                .domain(domain)
                .await
                .caused_by(trc::location!())?
                .is_some()
        {
            return Ok(Some(address));
        }
    }
    Ok(None)
}

/// Whether two domains share an organizational domain, by the public suffix
/// list.
fn same_organization(domain: &str, other: &str) -> bool {
    match (organizational_domain(domain), organizational_domain(other)) {
        (Some(domain), Some(other)) => domain == other,
        _ => false,
    }
}

fn organizational_domain(domain: &str) -> Option<String> {
    let domain = domain.to_ascii_domain()?.to_ascii_lowercase();
    let organization = psl::domain_str(&domain).unwrap_or(&domain);
    (!organization.is_empty()).then(|| organization.to_string())
}

