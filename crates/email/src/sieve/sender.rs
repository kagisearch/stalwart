//! FORK: restricts who a Sieve script can send mail as.
//!
//! A script chooses the From header of the vacation replies and notifications
//! it generates (`vacation :from`), and the runtime does not check it. These
//! messages are queued directly, so no submission check sees them either.
//! Only messages whose From is a single address of the account are sent, and
//! they are signed and sent as that address.

use crate::message::delivery::AutogeneratedMessage;
use common::Server;
use compact_str::CompactString;
use mail_parser::{HeaderName, MessageParser};
use sieve::MessageSource;
use trc::SieveEvent;

/// Drops the generated replies and notifications that are not from an address
/// of the account, and makes the rest use their From address as their sending
/// identity. `own_addresses` are addresses already known to be the account's:
/// its base address and the one the message was sent to, which is how a
/// sub-address, masked address or catch-all address is accepted.
/// Redirects keep the sender of the message they forward and are left alone.
pub(super) async fn retain_own_senders(
    server: &Server,
    account_id: u32,
    own_addresses: [&str; 2],
    generated: &mut Vec<AutogeneratedMessage>,
    session_id: u64,
) {
    let mut retained = Vec::with_capacity(generated.len());
    for mut message in generated.drain(..) {
        if message.source != MessageSource::Redirect {
            let from = from_address(&message.message);
            let mut is_own = false;
            if let Some(from) = &from {
                // Only an address listed on the account is looked up. Resolving
                // sub-addresses, masked addresses and catch-alls would accept a
                // masked local part on any hosted domain.
                is_own = own_addresses
                    .iter()
                    .any(|own| own.eq_ignore_ascii_case(from))
                    || matches!(
                        server.account_id_from_email(from, false).await,
                        Ok(Some(id)) if id == account_id
                    );
            }
            match from {
                Some(from) if is_own => message.account_address = from,
                from => {
                    trc::event!(
                        Sieve(SieveEvent::NotSupported),
                        SpanId = session_id,
                        From = CompactString::from(from.unwrap_or_default()),
                        Reason = "Generated message is not from an address of the account.",
                    );
                    continue;
                }
            }
        }
        retained.push(message);
    }
    *generated = retained;
}

/// The address in the From header, when there is exactly one of each.
fn from_address(raw_message: &[u8]) -> Option<String> {
    let message = MessageParser::new().parse(raw_message)?;
    if message.headers().all(HeaderName::From).count() != 1 {
        return None;
    }
    let mut mailboxes = message.from()?.mailboxes();
    let address = mailboxes.next()?.address()?;
    mailboxes.next().is_none().then(|| address.to_lowercase())
}
